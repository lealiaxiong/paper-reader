import type { SourceId } from "./sources";

/** How a paper's reader data was produced. */
export type PaperProvenance = "deterministic" | "byom";

/** Source format the extraction came from. */
export type PaperFormat = "html" | "pdf";

export interface Figure {
  /** Stable internal id, e.g. "f1" */
  id: string;
  /** Display label, e.g. "Figure 1" */
  label: string;
  /** Figure number parsed from caption (1-based), if available */
  number: number | null;
  /** "figure" | "table" — distinguishes Figure N from Table N in the regex map */
  kind: "figure" | "table";
  caption: string;
  imageUrl: string | null;
  /** For figures that are HTML tables (no image file): the table's HTML markup */
  tableHtml?: string | null;
  /** Plain-English gloss generated by Muse Ember from caption + citing paragraphs */
  explanation?: string;
  /** 1-based page in the source PDF, for client-side crops (BYOM) */
  pdfPage?: number;
  /** Normalized [x, y, w, h] in [0,1] on the source PDF page (BYOM) */
  bbox?: [number, number, number, number];
}

export interface Paragraph {
  /** Stable internal id, e.g. "p12" */
  id: string;
  /** Plain text (plain fallback, also used for regex mapping) */
  text: string;
  /** HTML with inline math markers (@@K{n}@@) and <a> links — for display */
  html: string;
  /** Raw TeX strings for each @@K{n}@@ in this paragraph, in order */
  mathTex: string[];
}

export interface ReaderData {
  source: SourceId;
  sourceId: string;
  title: string;
  authors: string[];
  paragraphs: Paragraph[];
  figures: Figure[];
  /** paraId -> [figureId, ...] */
  paraFigureMap: Record<string, string[]>;
  /** Extraction provenance; absent on legacy cached entries (deterministic). */
  provenance?: PaperProvenance;
  /** Source format; absent on legacy cached entries (html). */
  format?: PaperFormat;
}

/**
 * Client-facing paper data. `Paragraph.text` is only needed server-side (regex
 * mapping + explanations), so it is stripped before caching/responding.
 */
export interface ReaderPayload extends Omit<ReaderData, "paragraphs"> {
  paragraphs: Omit<Paragraph, "text">[];
}
